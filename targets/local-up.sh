#!/usr/bin/env bash
# Lab 2, Part A (no-Azure path): start two local "servers" as containers.
#
#   web1: SSH on localhost:2221, HTTP on localhost:8081
#   web2: SSH on localhost:2222, HTTP on localhost:8082
#
# Writes inventory/generated.ini with the connection details.
# Safe to re-run: existing containers are replaced.
set -euo pipefail
cd "$(dirname "$0")/.."

KEY="${KEY:-$HOME/.ssh/cao_lab}"
[[ -f "$KEY" ]] || ssh-keygen -q -t ed25519 -N "" -f "$KEY" -C "cao-lab"

echo "==> Building the node image"
docker build -q -t cao-node --build-arg PUBKEY="$(cat "$KEY.pub")" targets/node >/dev/null

for i in 1 2; do
  docker rm -f "web$i" >/dev/null 2>&1 || true
  docker run -d --name "web$i" --hostname "web$i" \
    -p "222$i:22" -p "808$i:80" cao-node >/dev/null
  echo "    web$i started (ssh localhost:222$i, http localhost:808$i)"
done

cat > inventory/generated.ini <<EOF
# Generated by targets/local-up.sh. Copy these lines into inventory/hosts.ini.
web1 ansible_host=127.0.0.1 ansible_port=2221
web2 ansible_host=127.0.0.1 ansible_port=2222
EOF

echo "==> Done. Connection details are in inventory/generated.ini"
