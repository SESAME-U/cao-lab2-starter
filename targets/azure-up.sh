#!/usr/bin/env bash
# Lab 2, Part A (Azure path): create two small Ubuntu VMs for Ansible to manage.
#
# Imperative on purpose: this is the "scripted provisioning" step of the
# maturity ladder. In week 5 you rewrite it declaratively with Terraform.
#
# Cost: two Standard_B1s VMs. Destroy them at the end of the lab with
#   ./targets/azure-down.sh
#
# If Azure refuses the region ("RequestDisallowedByPolicy"), your student
# subscription limits regions: run again with e.g.  LOCATION=francecentral
set -euo pipefail
cd "$(dirname "$0")/.."

LOCATION="${LOCATION:-westeurope}"
OWNER="${GITHUB_USER:-$(whoami)}"
RG="${RG:-rg-cao-lab2-$OWNER}"
KEY="${KEY:-$HOME/.ssh/cao_lab}"
SIZE="${SIZE:-Standard_B1s}"

az account show >/dev/null || { echo "Run 'az login --use-device-code' first."; exit 1; }
[[ -f "$KEY" ]] || ssh-keygen -q -t ed25519 -N "" -f "$KEY" -C "cao-lab"

echo "==> Resource group $RG in $LOCATION"
az group create -n "$RG" -l "$LOCATION" --tags course=cao owner="$OWNER" lab=2 -o none

: > inventory/generated.ini
echo "# Generated by targets/azure-up.sh. Copy these lines into inventory/hosts.ini." >> inventory/generated.ini

for i in 1 2; do
  echo "==> VM web$i (2 to 3 minutes)"
  az vm create -g "$RG" -n "web$i" \
    --image Ubuntu2404 --size "$SIZE" \
    --admin-username azureuser --ssh-key-values "$KEY.pub" \
    --public-ip-sku Standard --tags course=cao owner="$OWNER" lab=2 \
    -o none
  az vm open-port -g "$RG" -n "web$i" --port 80 --priority 1010 -o none
  ip=$(az vm show -d -g "$RG" -n "web$i" --query publicIps -o tsv)
  echo "web$i ansible_host=$ip" >> inventory/generated.ini
  echo "    web$i: $ip"
done

echo "==> Done. Connection details are in inventory/generated.ini"
